/* ==================== تصنيف نوع السكريبت ====================
 * ترجمة مبسّطة (keyword-based) لمنطق "pick format" في SKILL.md.
 * هدفها تحميل ملف القواعد الصحيح لكل شكل فيديو، بدل تحميل كل
 * الأنواع الـ14 في كل طلب (يوفّر توكنز وبيرفع الدقة).
 */
function agency_classify_script_format(string $sourceText): string {
    $t = mb_strtolower($sourceText);
    $has = fn(array $words) => array_reduce($words, fn($acc, $w) => $acc || mb_strpos($t, $w) !== false, false);

    if ($has(['مقابلة', 'أسئلة', 'كيس ستادي', 'case study questions'])) return 'case_study_questions';
    if ($has(['قصة نجاح', 'إزاي عمل', 'إزاي حقق', 'case study', 'دراسة حالة'])) return 'case_study';
    if ($has(['مهما يحصل', 'مفارقة', 'سر', 'لغز', 'مستني الآخر'])) return 'premise';
    if ($has(['حدث واحد', 'يوم واحد', 'تجربة غيرت', 'كل ما تعلمته من'])) return 'framing_device';
    if ($has(['إزاي تعمل', 'طريقة', 'خطوات', 'how to', 'شرح خطوة بخطوة'])) return 'how_to';
    if ($has(['اعمل', 'متعملش', 'افعل', 'لا تفعل', 'keep', 'avoid'])) return 'keep_avoid';
    if ($has(['مستويات', 'درجات', 'من الأسوأ للأفضل', 'levels', 'tiers'])) return 'ladder';
    if ($has(['دروس', 'تعلمتها', 'lessons', 'أهم دروس'])) return 'lessons';
    if ($has(['أسعار', 'باقات', 'خيارات بالسعر', 'price', 'تكلفة'])) return 'price_ladder';
    if ($has(['عملية مستمرة', 'رحلة العميل', 'sales process', 'من البداية للنهاية'])) return 'process_flow';
    if ($has(['إيجابيات', 'سلبيات', 'مميزات وعيوب', 'pros', 'cons'])) return 'pros_cons';
    if ($has(['ترتيب', 'أفضل', 'الأقوى', 'ranking', 'مقارنة بين عدة'])) return 'ranking';
    if ($has(['نتيجة واحدة', 'ربح كام', 'حققت كام', 'النتيجة اللي حصلت'])) return 'result';
    if ($has(['لايف', 'جلسة حوار', 'mastermind', 'جلسة نقاش'])) return 'mastermind';

    return 'how_to'; // افتراضي آمن: أغلب طلبات "اعمل سكريبت" شرح خطوات
}


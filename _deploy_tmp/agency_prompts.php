function agency_build_scriptwriter_prompt(string $sourceText): string {
    $format = agency_classify_script_format($sourceText);
    return AGENCY_SHARED_RULES . "\n[دورك: كاتب سكريبتات يوتيوب محترف داخل فريق Flovo. مهمتك الوحيدة كتابة سكريبت فيديو جاهز للتنفيذ بناءً على المصدر اللي يعطيه المستخدم (ملاحظات صوتية، بحث، أو مواضيع).]\n\n"
        . agency_scriptwriter_core_rules() . "\n\n" . agency_script_format_rules($format);
}

